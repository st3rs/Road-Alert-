export const BANGKOK_BOUNDS = {
  minLat: 13.695,
  maxLat: 13.83,
  minLng: 100.515,
  maxLng: 100.64,
};

export const SVG_VIEWBOX = {
  width: 1000,
  height: 1200,
};

export function latLngToSvg(pos: LatLng): { x: number; y: number } {
  const xNorm =
    (pos.lng - BANGKOK_BOUNDS.minLng) /
    (BANGKOK_BOUNDS.maxLng - BANGKOK_BOUNDS.minLng);
  const yNorm =
    1 -
    (pos.lat - BANGKOK_BOUNDS.minLat) /
      (BANGKOK_BOUNDS.maxLat - BANGKOK_BOUNDS.minLat);
  return {
    x: xNorm * SVG_VIEWBOX.width,
    y: yNorm * SVG_VIEWBOX.height,
  };
}

export function svgToLatLng(x: number, y: number): LatLng {
  const xNorm = x / SVG_VIEWBOX.width;
  const yNorm = y / SVG_VIEWBOX.height;
  return {
    lat:
      BANGKOK_BOUNDS.minLat +
      (1 - yNorm) * (BANGKOK_BOUNDS.maxLat - BANGKOK_BOUNDS.minLat),
    lng:
      BANGKOK_BOUNDS.minLng +
      xNorm * (BANGKOK_BOUNDS.maxLng - BANGKOK_BOUNDS.minLng),
  };
}

